"""
Demand Generation Engine
Combines organic baseline, seasonal effects, price elasticity, and customer repeat orders.
"""
import random
from typing import Dict, Any

class DemandEngine:
    def __init__(self, rng: random.Random):
        self.rng = rng

    def get_day_of_week_factor(self, day: int, business_type: str) -> float:
        """
        Calculates day-of-week demand multipliers (1-indexed day, 1=Monday).
        Different businesses have distinct weekday/weekend profiles in India.
        """
        day_of_week = ((day - 1) % 7) + 1  # 1=Mon, 2=Tue, 3=Wed, 4=Thu, 5=Fri, 6=Sat, 7=Sun

        if business_type == "home_tiffin":
            # High Mon-Fri for working lunches, drops on weekends
            return 1.15 if day_of_week <= 5 else 0.65
        elif business_type in ("home_bakery", "salon_service", "cloud_kitchen", "handicraft_business"):
            # Spikes Fri-Sun for treats, grooming, leisure dining
            if day_of_week in (6, 7):
                return 1.40
            elif day_of_week == 5:
                return 1.15
            else:
                return 0.85
        elif business_type in ("reseller_kirana", "packaged_food"):
            # Slight lift on weekends for grocery stocking
            return 1.15 if day_of_week in (6, 7) else 0.95
        else:
            # Fabrication, repair, tailoring
            return 0.80 if day_of_week == 7 else 1.05

    def calculate_price_elasticity_factor(
        self,
        current_price: float,
        baseline_price: float,
        elasticity: float = -1.2,
    ) -> float:
        """
        Standard economic price elasticity multiplier: (P / P_base) ^ elasticity.
        """
        if baseline_price <= 0 or current_price <= 0:
            return 1.0
        price_ratio = current_price / baseline_price
        # Guard against extreme ratios
        price_ratio = max(0.4, min(2.5, price_ratio))
        return price_ratio ** elasticity

    def generate_orders(
        self,
        day: int,
        business_type: str,
        base_demand: float,
        demand_variability: float,
        current_price: float,
        baseline_price: float,
        new_customer_orders: int,
        repeat_customer_orders: int,
    ) -> int:
        """
        Calculates total daily customer orders.
        Causally generated by active/retained customers and newly acquired customers,
        modulated by day-of-week seasonality, price elasticity, and market variability.
        Eliminates duplicate independent organic demand stream.
        """
        dow_factor = self.get_day_of_week_factor(day, business_type)
        price_factor = self.calculate_price_elasticity_factor(current_price, baseline_price)

        variance = self.rng.uniform(-demand_variability, demand_variability)
        market_multiplier = max(0.0, dow_factor * price_factor * (1.0 + variance))

        customer_orders = new_customer_orders + repeat_customer_orders
        if customer_orders > 0:
            total_orders = int(round(customer_orders * market_multiplier))
            return max(1, total_orders)
        elif base_demand > 0:
            # Fallback for standalone/legacy unit tests without customer state
            total_orders = int(round(base_demand * market_multiplier))
            return max(1, total_orders)
        return 0
