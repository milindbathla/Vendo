# ── chat ────────────────────────────────────────────────────────────────────
class ChatIn(BaseModel):
    message: str


_PANELS = [
    ("accounts", ("cash", "money", "balance", "afford", "spend", "pay", "due", "salary", "bill pay", "profit")),
    ("inventory", ("stock", "inventory", "low", "running", "reorder", "out of", "oil", "dal", "rice", "ingredient", "kitchen")),
    ("invoices", ("invoice", "bill", "supplier", "gupta", "packaging", "gst", "purchase")),
    ("reviews", ("review", "rating", "feedback", "reputation", "customers say", "stars")),
    ("market", ("near", "nearby", "demand", "market", "competitor", "area", "segment", "footfall", "who", "neighbour", "neighbor")),
]


def _route(message: str) -> str:
    m = message.lower()
    for panel, keys in _PANELS:
        if any(k in m for k in keys):
            return panel
    return "overview"


_BUILDERS = {
    "accounts": build_accounts, "inventory": build_inventory, "invoices": build_invoices,
    "market": build_market, "reviews": build_reviews, "overview": build_overview,
}


def _fallback_reply(panel: str, d: Dict[str, Any]) -> str:
    if panel == "accounts":
        head = d["upcoming"][0]["payee"] if d["upcoming"] else "nothing urgent"
        return (f"You have {_rupees(d['balance'])} in hand. After keeping your {_rupees(d['min_buffer'])} "
                f"buffer, {_rupees(d['usable'])} is free — but {_rupees(d['total_due'])} is due this week, "
                f"starting with {head}.")
    if panel == "inventory":
        crit = [i['name'] for i in d['items'] if i['status'] == 'critical']
        names = ", ".join(crit[:3]) if crit else "nothing"
        return (f"{d['critical_count']} items are below their reorder point — {names}. "
                f"{d['low_count']} more are getting low, worth topping up on your next order.")
    if panel == "invoices":
        n = len(d["docs"]); latest = d["docs"][0] if d["docs"] else None
        tail = f" The latest is {latest['supplier']} for {_rupees(latest['total'])}." if latest else ""
        return f"You have {n} supplier invoices on file, {_rupees(d['total'])} in all.{tail}"
    if panel == "reviews":
        return f"You're at {d['avg']} stars across {d['count']} reviews, {d['positive_pct']}% of them positive."
    if panel == "market":
        top = d["segments"][0] if d["segments"] else None
        if top:
            return (f"Around {d['locality']}, your strongest demand is {top['segment'].replace('_',' ')} — "
                    f"about {top['est_households']:,} households, {round(top['interest_score']*100)}% interest, "
                    f"{top['distance_km']} km away.")
        return f"I'm looking at demand around {d['locality']}."
    return (f"Quick read: {_rupees(d['balance'])} in the bank, {_rupees(d['total_due'])} due this week, "
            f"{d['low_count']} items low on stock, and a {d['avg']}-star reputation.")


def _gemini_reply(message: str, panel: str, data: Dict[str, Any]) -> Optional[str]:
    api_key = os.environ.get("GEMINI_API_KEY")
    if not api_key:
        return None
    try:
        from google import genai
        client = genai.Client(api_key=api_key)
        biz = _one("SELECT business_name, owner_name, locality, city FROM business_profile LIMIT 1") or {}
        prompt = (
            "You are Alexa+, a warm, concise voice assistant for an Indian micro-business owner. "
            f"The shop is {biz.get('business_name')} in {biz.get('locality')}, {biz.get('city')}; "
            f"owner {biz.get('owner_name')}. Answer the owner's question in at most 3 short spoken "
            "sentences, plain text (this will be read aloud — no markdown, no bullet points). "
            "Use rupee figures naturally. Ground every number ONLY in this JSON data:\n"
            f"{json.dumps(data, default=str)}\n\n"
            f"Owner asked: {message}"
        )
        model = os.environ.get("GEMINI_MODEL", "gemini-2.5-flash")
        resp = client.models.generate_content(model=model, contents=prompt)
        text = (getattr(resp, "text", "") or "").strip()
        return text or None
    except Exception:
        return None


@router.post("/chat")
def chat(body: ChatIn) -> Dict[str, Any]:
    panel = _route(body.message)
    data = _BUILDERS[panel]()
    reply = _gemini_reply(body.message, panel, data)
    source = "gemini" if reply else "demo"
    if not reply:
        reply = _fallback_reply(panel, data)
    return {"reply": reply, "source": source, "panel": panel, "data": data}
