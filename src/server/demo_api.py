"""
alexa+ vendo — panel + chat API (MCP-backed)
============================================
Read-only endpoints that back the alexa+ vendo frontend (onboarding form is
static; the Alexa+ interface reads these).

1. **The MCP server is genuinely exercised.** Every panel of data the frontend
   shows is fetched by calling a tool on the *same* FastMCP server instance that
   is mounted at ``/mcp`` (shared in via :func:`set_mcp_server`). The business
   data lives behind MCP tools (``get_cash_position``, ``get_inventory_status``,
   ``get_supplier_invoices`` … reading the business database). Each call is
   recorded in an activity log exposed at ``/api/mcp/activity``.

2. **Inference.** The spoken reply is generated by an LLM (Anthropic Claude if
   ``ANTHROPIC_API_KEY`` is set, otherwise Google Gemini via ``GEMINI_API_KEY``),
   grounded strictly in the MCP tool output. With no key, a deterministic
   responder over the same data keeps the app running. The provider is never
   exposed to the client.

The database is opened read-only; this module never writes to it.
"""
import json
import logging
import os
import re
import sqlite3
import time
from collections import deque
from typing import Any, Dict, List, Optional, Tuple

from fastapi import APIRouter
from pydantic import BaseModel

from src.db.connection import DEFAULT_DB_PATH

logger = logging.getLogger(__name__)
router = APIRouter(prefix="/api", tags=["demo"])

_CLAUDE_MODEL = os.environ.get("ANTHROPIC_MODEL", "claude-opus-5-5")
_GEMINI_MODEL = os.environ.get("GEMINI_MODEL", "gemini-2.5-flash")


def _real(v: Optional[str]) -> bool:
    """True only for a key that looks like a real value (not an empty/placeholder)."""
    v = (v or "").strip()
    return bool(v) and not v.lower().startswith("your") and v.lower() not in ("changeme", "none", "null")


def _provider() -> str:
    """Which LLM writes the spoken reply: Claude if its key is set, else free Gemini, else none."""
    if _real(os.environ.get("ANTHROPIC_API_KEY")):
        return "claude"
    if _real(os.environ.get("GEMINI_API_KEY")):
        return "gemini"
    return "demo"


def _llm_model() -> str:
    p = _provider()
    return _CLAUDE_MODEL if p == "claude" else _GEMINI_MODEL if p == "gemini" else "deterministic"


# ── shared MCP server (handed in by web_app so we hit the mounted instance) ──
_MCP: Any = None
_DEMO_TOOLS_REGISTERED = False
_ACTIVITY: "deque[Dict[str, Any]]" = deque(maxlen=50)


def set_mcp_server(server: Any) -> None:
    """Share the mounted FastMCP server and register the business data tools on it."""
    global _MCP
    _MCP = server
    _register_data_tools(server)


def _register_data_tools(server: Any) -> None:
    """Additively expose the business database as MCP tools (never overrides teammate tools)."""
    global _DEMO_TOOLS_REGISTERED
    if _DEMO_TOOLS_REGISTERED or server is None:
        return

    @server.tool(name="get_cash_position")
    def get_cash_position() -> Dict[str, Any]:
        """Cash balance, safe-to-spend buffer and upcoming payments."""
        return build_accounts()

    @server.tool(name="get_inventory_status")
    def get_inventory_status() -> Dict[str, Any]:
        """Kitchen stock levels with reorder status."""
        return build_inventory()

    @server.tool(name="get_supplier_invoices")
    def get_supplier_invoices() -> Dict[str, Any]:
        """Supplier invoices with line items and tax breakdown from Zoho Books."""
        return build_invoices()

    @server.tool(name="get_market_demand")
    def get_market_demand() -> Dict[str, Any]:
        """Neighbourhood customer-demand segments around the business."""
        return build_market()

    @server.tool(name="get_customer_reviews")
    def get_customer_reviews() -> Dict[str, Any]:
        """Customer reviews with ratings and sentiment."""
        return build_reviews()

    @server.tool(name="get_business_overview")
    def get_business_overview() -> Dict[str, Any]:
        """One-glance snapshot across cash, stock and reputation."""
        return build_overview()

    _DEMO_TOOLS_REGISTERED = True
    logger.info("Registered business data tools on the mounted MCP server.")


# ── MCP invocation + activity log ───────────────────────────────────────────
def _record(tool: str, ok: bool, mode: str, ms: int, n: Optional[int]) -> None:
    _ACTIVITY.appendleft({
        "ts": time.strftime("%H:%M:%S"), "tool": tool,
        "ok": ok, "mode": mode, "ms": ms, "n": n,
    })


def _ensure_mcp() -> Any:
    """Return the mounted MCP server, lazily attaching it if needed. Never None.

    There is deliberately NO non-MCP data path: every panel fetch must go through
    the MCP server, so the server is guaranteed to be called on every prompt."""
    global _MCP
    if _MCP is None:
        try:  # self-heal: grab the instance web_app mounted at /mcp
            from src.server import web_app as _wa
            set_mcp_server(_wa.mcp_server)
        except Exception as e:  # pragma: no cover
            logger.error("Could not attach MCP server: %s", e)
    if _MCP is None:
        raise RuntimeError("MCP server not attached — data can only be served through MCP.")
    return _MCP


async def _mcp_call(tool: str, args: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """Call a tool on the mounted MCP server and unwrap its structured result."""
    t0 = time.time()
    server = _ensure_mcp()
    try:
        res = await server.call_tool(tool, args or {})
        _content, structured = res  # FastMCP: (content_blocks, {"result": {...}})
        data = structured.get("result", structured) if isinstance(structured, dict) else structured
        mode = "live" if (isinstance(data, dict) and data.get("is_mock") is False) else "mcp"
        _record(tool, True, mode, int((time.time() - t0) * 1000), _count(data))
        return data
    except Exception as e:
        logger.warning("MCP call %s failed: %s", tool, e)
        _record(tool, False, "error", int((time.time() - t0) * 1000), None)
        raise


def _count(d: Any) -> Optional[int]:
    if isinstance(d, dict):
        for k in ("items", "docs", "upcoming", "segments", "data"):
            if isinstance(d.get(k), list):
                return len(d[k])
    return None


# ── read-only db access ─────────────────────────────────────────────────────
def _db_path() -> str:
    return os.environ.get("DATABASE_PATH", DEFAULT_DB_PATH)


def q(sql: str, params: tuple = ()) -> List[Dict[str, Any]]:
    uri = f"file:{_db_path()}?mode=ro"
    conn = sqlite3.connect(uri, uri=True)
    conn.row_factory = sqlite3.Row
    try:
        return [dict(r) for r in conn.execute(sql, params).fetchall()]
    finally:
        conn.close()


def _one(sql: str, params: tuple = ()) -> Optional[Dict[str, Any]]:
    rows = q(sql, params)
    return rows[0] if rows else None


def _rupees(n: float) -> str:
    try:
        return "₹" + f"{float(n):,.0f}"
    except Exception:
        return "₹" + str(n)


def _llm_enabled() -> bool:
    return _provider() != "demo"


# ── data builders (the demo.db source behind the MCP demo tools) ─────────────
def build_business() -> Dict[str, Any]:
    b = _one("SELECT * FROM business_profile LIMIT 1") or {}
    b["ai_enabled"] = _llm_enabled()   # the assistant brain is online (provider not exposed)
    return b


def build_accounts() -> Dict[str, Any]:
    cash = _one("SELECT * FROM cash_position ORDER BY as_of DESC LIMIT 1") or {}
    pays = q(
        "SELECT payee, category, amount, due_date, status FROM upcoming_payments "
        "WHERE status='pending' ORDER BY due_date"
    )
    balance = float(cash.get("current_balance", 0))
    buffer = float(cash.get("min_cash_buffer", 0))
    total_due = sum(float(p["amount"]) for p in pays)
    return {
        "balance": balance,
        "min_buffer": buffer,
        "usable": round(balance - buffer, 2),
        "total_due": round(total_due, 2),
        "upcoming": pays,
    }


def build_inventory() -> Dict[str, Any]:
    rows = q(
        "SELECT i.name, i.unit, i.reorder_point, i.par_level, s.stock_qty "
        "FROM inventory_stock s JOIN items i ON i.item_id = s.item_id "
        "ORDER BY (s.stock_qty * 1.0 / NULLIF(i.reorder_point,0))"
    )
    items, crit, low = [], 0, 0
    for r in rows:
        stock = float(r["stock_qty"]); reorder = float(r["reorder_point"]); par = float(r["par_level"])
        if stock < reorder:
            status = "critical"; crit += 1
        elif stock < par:
            status = "low"; low += 1
        else:
            status = "ok"
        items.append({
            "name": r["name"], "unit": r["unit"],
            "stock": round(stock, 2), "reorder": round(reorder, 2), "status": status,
        })
    return {"items": items, "critical_count": crit, "low_count": low}


def build_invoices() -> Dict[str, Any]:
    docs_raw = q("SELECT * FROM business_documents WHERE doc_type='invoice' ORDER BY doc_date DESC")
    names = {r["item_id"]: r["name"] for r in q("SELECT item_id, name FROM items")}
    docs, total = [], 0.0
    for d in docs_raw:
        try:
            ex = json.loads(d.get("extracted_json") or "{}")
        except Exception:
            ex = {}
        lines = [{
            "item": names.get(l.get("item_id"), l.get("item_id")),
            "qty": l.get("qty"), "unit_price": l.get("unit_price"), "total": l.get("total"),
        } for l in ex.get("lines", [])]
        amt = float(ex.get("total_amount", 0))
        total += amt
        docs.append({
            "supplier": ex.get("supplier", d.get("supplier_id")),
            "invoice_number": ex.get("invoice_number", d.get("doc_id")),
            "date": ex.get("date", d.get("doc_date")),
            "taxable": ex.get("taxable_amount"), "tax": ex.get("tax_amount"), "total": amt,
            "confidence": d.get("extraction_confidence"), "lines": lines,
        })
    return {"docs": docs, "total": round(total, 2), "source": "Zoho Books"}


def build_market() -> Dict[str, Any]:
    biz = _one("SELECT locality, city FROM business_profile LIMIT 1") or {}
    segs = q(
        "SELECT segment, est_households, budget_per_meal, interest_score, distance_km, competitor_density "
        "FROM potential_customer_segments WHERE locality=? ORDER BY interest_score DESC LIMIT 6",
        (biz.get("locality"),),
    ) or q(
        "SELECT segment, est_households, budget_per_meal, interest_score, distance_km, competitor_density "
        "FROM potential_customer_segments ORDER BY interest_score DESC LIMIT 6"
    )
    segments = [{
        "segment": s["segment"], "est_households": s["est_households"],
        "budget": s["budget_per_meal"], "interest_score": s["interest_score"],
        "distance_km": s["distance_km"], "competitor_density": s["competitor_density"],
    } for s in segs]
    return {"locality": biz.get("locality"), "city": biz.get("city"), "segments": segments}


def build_reviews() -> Dict[str, Any]:
    rows = q("SELECT author_name, source, rating, text, date, sentiment FROM internet_reviews ORDER BY date DESC")
    if not rows:
        return {"avg": 0, "count": 0, "positive_pct": 0, "items": []}
    avg = round(sum(float(r["rating"]) for r in rows) / len(rows), 1)
    pos = round(100 * sum(1 for r in rows if r["sentiment"] == "positive") / len(rows))
    items = [{
        "author": r["author_name"], "source": r["source"], "rating": int(r["rating"]),
        "text": r["text"], "date": r["date"],
    } for r in rows[:5]]
    return {"avg": avg, "count": len(rows), "positive_pct": pos, "items": items}


def build_overview() -> Dict[str, Any]:
    acc = build_accounts(); inv = build_inventory(); rev = build_reviews()
    return {
        "balance": acc["balance"], "total_due": acc["total_due"],
        "low_count": inv["critical_count"] + inv["low_count"], "avg": rev["avg"],
    }


