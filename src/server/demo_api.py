# ── chat (MCP for data, Claude for the spoken reply) ─────────────────────────
class ChatIn(BaseModel):
    message: str


def _fallback_reply(panel: str, d: Dict[str, Any]) -> str:
    if panel == "accounts":
        head = d["upcoming"][0]["payee"] if d.get("upcoming") else "nothing urgent"
        return (f"You have {_rupees(d['balance'])} in hand. After keeping your {_rupees(d['min_buffer'])} "
                f"buffer, {_rupees(d['usable'])} is free, but {_rupees(d['total_due'])} is due this week, "
                f"starting with {head}.")
    if panel == "inventory":
        crit = [i['name'] for i in d.get('items', []) if i['status'] == 'critical']
        names = ", ".join(crit[:3]) if crit else "nothing"
        return (f"{d['critical_count']} items are below their reorder point, {names}. "
                f"{d['low_count']} more are getting low, worth topping up on your next order.")
    if panel == "invoices":
        n = len(d.get("docs", [])); latest = d["docs"][0] if d.get("docs") else None
        tail = f" The latest is {latest['supplier']} for {_rupees(latest['total'])}." if latest else ""
        return f"You have {n} invoices on file, {_rupees(d.get('total', 0))} in all.{tail}"
    if panel == "reviews":
        return f"You are at {d['avg']} stars across {d['count']} reviews, {d['positive_pct']}% of them positive."
    if panel == "market":
        top = d["segments"][0] if d.get("segments") else None
        if top:
            return (f"Around {d['locality']}, your strongest demand is {top['segment'].replace('_',' ')}, "
                    f"about {top['est_households']:,} households, {round(top['interest_score']*100)}% interest, "
                    f"{top['distance_km']} km away.")
        return f"I'm looking at demand around {d['locality']}."
    return (f"Quick read: {_rupees(d.get('balance', 0))} in the bank, {_rupees(d.get('total_due', 0))} due this week, "
            f"{d.get('low_count', 0)} items low on stock, and a {d.get('avg', 0)}-star reputation.")


_SYSTEM_PROMPT = (
    "You are Alexa+, a warm, concise voice assistant for an Indian micro-business owner. "
    "Answer in at most three short spoken sentences, plain text that will be read aloud: "
    "no markdown, no bullet points, no em dashes. Use rupee figures naturally (say 'rupees'). "
    "Ground every number ONLY in the DATA provided by the MCP server; never invent a number."
)


def _build_prompt(message: str, data: Dict[str, Any], biz: Dict[str, Any]) -> str:
    return (
        f"Shop: {biz.get('business_name')} in {biz.get('locality')}, {biz.get('city')} "
        f"(owner {biz.get('owner_name')}).\n"
        f"The owner asked: {message}\n\n"
        f"DATA (JSON, fetched from the MCP server):\n{json.dumps(data, default=str)}"
    )


def _llm_text(system: str, user: str, max_tokens: int = 400, short: bool = False) -> Optional[str]:
    """One LLM turn via whichever provider is configured (Claude, else free Gemini).

    ``short`` makes it deterministic and terse (used for intent classification)."""
    p = _provider()
    try:
        if p == "claude":
            import anthropic
            client = anthropic.Anthropic()  # reads ANTHROPIC_API_KEY from the environment
            resp = client.messages.create(
                model=_CLAUDE_MODEL, max_tokens=(10 if short else max_tokens), system=system,
                messages=[{"role": "user", "content": user}],
            )
            return "".join(b.text for b in resp.content if getattr(b, "type", None) == "text").strip() or None
        if p == "gemini":
            from google import genai
            client = genai.Client(api_key=os.environ.get("GEMINI_API_KEY"))
            cfg = None
            if short:
                # one-word, deterministic, no thinking so the tiny budget is all output
                cfg = {"temperature": 0, "max_output_tokens": 10, "thinking_config": {"thinking_budget": 0}}
            resp = client.models.generate_content(
                model=_GEMINI_MODEL, contents=system + "\n\n" + user, config=cfg
            )
            return (getattr(resp, "text", "") or "").strip() or None
    except Exception as e:
        logger.warning("LLM call failed (%s): %s", p, e)
    return None


def _llm_reply(message: str, data: Dict[str, Any], biz: Dict[str, Any]) -> Optional[str]:
    """Spoken reply, grounded strictly in the MCP data."""
    return _llm_text(_SYSTEM_PROMPT, _build_prompt(message, data, biz), 400)


# ── intent routing: let the LLM map the question to a panel (handles Hinglish) ──
_INTENT_PANEL = {
    "cash": "accounts", "inventory": "inventory", "invoices": "invoices",
    "reviews": "reviews", "market": "market", "overview": "overview",
}

_CLASSIFY_SYS = (
    "You route an Indian shop owner's question to ONE data category. "
    "The question may be in English, Hindi, or Hinglish. Reply with ONLY one lowercase word from this list:\n"
    "cash - money, bank balance, cash in hand, payments due, can I afford, spending, profit (paisa, balance)\n"
    "inventory - stock, ingredients, raw material, supplies needed to cook/make orders, what to buy or reorder "
    "(saaman, maal, stock, kitna chahiye, order banane ke liye)\n"
    "invoices - supplier invoices, vendor bills, GST, purchases FROM suppliers\n"
    "reviews - customer reviews, ratings, feedback, reputation, what customers say (customer feedback)\n"
    "market - demand around me, nearby customers, competitors, neighbourhood, who is ordering\n"
    "overview - a general 'how is my business / everything today' summary\n"
    "Reply with exactly one word, nothing else."
)


def _classify_intent(message: str) -> str:
    """LLM-based intent routing with the keyword router as a fallback."""
    out = _llm_text(_CLASSIFY_SYS, "Question: " + message, short=True)
    if out:
        toks = re.findall(r"[a-z]+", out.lower())
        # trust only a clean, short classification (one or two words)
        if toks and len(toks) <= 2:
            for t in toks:
                if t in _INTENT_PANEL:
                    return _INTENT_PANEL[t]
    return _route(message)  # deterministic fallback when no LLM / unexpected output


@router.post("/chat")
async def chat(body: ChatIn) -> Dict[str, Any]:
    panel = _classify_intent(body.message)
    biz = build_business()
    data, mcp_tools = await _fetch_panel(panel)
    reply = _llm_reply(body.message, data, biz)
    if not reply:
        reply = _fallback_reply(panel, data)
    # Response is provider-agnostic: the UI shows the MCP tool that served the data,
    # never which model wrote the sentence.
    return {
        "reply": reply,
        "panel": panel,
        "data": data,
        "mcp": {"tools": mcp_tools},
    }
