_PANEL_TOOL = {
    "accounts": "get_cash_position", "inventory": "get_inventory_status",
    "invoices": "get_supplier_invoices", "market": "get_market_demand",
    "reviews": "get_customer_reviews", "overview": "get_business_overview",
}

_PANELS = [
    ("accounts", ("cash", "money", "balance", "afford", "spend", "pay", "due", "salary", "bill pay", "profit")),
    ("inventory", ("stock", "inventory", "low", "running", "reorder", "out of", "oil", "dal", "rice", "ingredient", "kitchen", "saaman", "samaan", "maal", "chahiye", "banane")),
    ("reviews", ("review", "rating", "feedback", "reputation", "customers say", "customer feedback", "stars")),
    ("invoices", ("invoice", "bill", "supplier", "gupta", "packaging", "gst", "purchase", "zoho", "receivable", "payable")),
    ("market", ("near", "nearby", "demand", "market", "competitor", "area", "segment", "footfall", "who", "neighbour", "neighbor")),
]


def _route(message: str) -> str:
    m = message.lower()
    for panel, keys in _PANELS:
        if any(k in m for k in keys):
            return panel
    return "overview"


async def _fetch_panel(panel: str) -> Tuple[Dict[str, Any], List[str]]:
    tool = _PANEL_TOOL.get(panel, "get_business_overview")
    data = await _mcp_call(tool, {})
    return data, [tool]


